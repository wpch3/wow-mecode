-- ------------------------------------------------------------
-- 查1  AHBot 账号下面有没有角色
-- ------------------------------------------------------------
-- 你的 conf: AuctionHouseBot.Account = 2
-- 核心启动时跑的就是这条（CharacterDatabase.cpp:409）:
--     SELECT guid FROM characters WHERE account = ?
-- 如果这里【一行都没有】-> GetRandChar() 返回 0
--     -> 挂单的 owner = 0 -> 卖家名是空的
-- ------------------------------------------------------------
SELECT
    guid        AS 角色guid,
    account     AS 账号,
    name        AS 角色名,
    level       AS 等级,
    money       AS 铜钱,
    online      AS 在线
FROM characters
WHERE account = 2
ORDER BY guid;


-- ------------------------------------------------------------
-- 查2  拍卖行现在挂了多少货
-- ------------------------------------------------------------
SELECT COUNT(*) AS 挂单总数 FROM auctionhouse;


-- ------------------------------------------------------------
-- 查3  卖家分别是谁（本次体检最关键的一条）
-- ------------------------------------------------------------
-- 如果"卖家名"这一列大量出现【查不到名字】
--     -> 说明 owner 指向的角色不存在
--     -> 客户端拍卖行的卖家栏就是空白
-- ------------------------------------------------------------
SELECT
    a.itemowner                             AS 卖家guid,
    IFNULL(c.name, '【查不到名字】')         AS 卖家名,
    IFNULL(c.account, -1)                   AS 所属账号,
    COUNT(*)                                AS 挂单数
FROM auctionhouse a
LEFT JOIN characters c ON c.guid = a.itemowner
GROUP BY a.itemowner, c.name, c.account
ORDER BY 挂单数 DESC;


-- ------------------------------------------------------------
-- 查4  你的 pbot 角色在哪个账号
-- ------------------------------------------------------------
-- 决定第1步要不要把它们挪进 AHBot 账号
-- ------------------------------------------------------------
SELECT
    guid        AS 角色guid,
    account     AS 账号,
    name        AS 角色名,
    level       AS 等级,
    money       AS 铜钱
FROM characters
WHERE name IN ('鲤鱼', '卡特莉娜')
ORDER BY guid;


-- ------------------------------------------------------------
-- 查5  账号总览（看看哪些账号有角色，方便挑影子账号）
-- ------------------------------------------------------------
SELECT
    account         AS 账号,
    COUNT(*)        AS 角色数,
    GROUP_CONCAT(name ORDER BY guid SEPARATOR ', ') AS 角色列表
FROM characters
GROUP BY account
ORDER BY account;


-- ------------------------------------------------------------
-- 查6  拍卖行里的货是不是"凭空造"的
-- ------------------------------------------------------------
-- AHBot 造货走 AuctionHouseBotSeller.cpp:884 Item::CreateItem
-- 这些 item 在 item_instance 里 owner_guid = 0
-- ------------------------------------------------------------
SELECT
    IF(i.owner_guid = 0, 'AHBot凭空造的', '玩家挂的') AS 货物来源,
    COUNT(*) AS 数量
FROM auctionhouse a
LEFT JOIN item_instance i ON i.guid = a.itemguid
GROUP BY IF(i.owner_guid = 0, 'AHBot凭空造的', '玩家挂的');


