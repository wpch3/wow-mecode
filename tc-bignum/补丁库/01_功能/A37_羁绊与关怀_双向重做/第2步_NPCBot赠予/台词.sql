-- ============================================================================
--  第一部分：写入台词（REPLACE 可重复跑）
-- ============================================================================

REPLACE INTO `world`.`npc_text` (`ID`, `text0_0`, `text0_1`, `Probability0`) VALUES
(70801, '<赠予物品>',                        '<赠予物品>',                        1),
(70802, '谢谢你！我会好好收着的。',          '谢谢你！我会好好收着的。',          1),
(70803, '任务物品我不能收，你还用得上。',    '任务物品我不能收，你还用得上。',    1),
(70804, '这东西已经和你绑定了，我拿不了。',  '这东西已经和你绑定了，我拿不了。',  1),
(70805, '这是变出来的，过一会儿就没了。',    '这是变出来的，过一会儿就没了。',    1),
(70806, '背包我就不要了，我东西不多。',      '背包我就不要了，我东西不多。',      1),
(70807, '这个快过期了，你自己留着吧。',      '这个快过期了，你自己留着吧。',      1),
(70808, '你身上好像没有能给我的东西。',      '你身上好像没有能给我的东西。',      1);


-- ============================================================================
--  第二部分：验证（8 条都要有）
-- ============================================================================

SELECT '=== 台词写入结果，应该是 8 行 ===' AS `步骤`;

SELECT
    `ID`       AS `文本ID`,
    `text0_0`  AS `台词`,
    CASE `ID`
        WHEN 70801 THEN '菜单项'
        WHEN 70802 THEN '收下'
        WHEN 70803 THEN '拒绝-任务物品'
        WHEN 70804 THEN '拒绝-已绑定'
        WHEN 70805 THEN '拒绝-魔法造物'
        WHEN 70806 THEN '拒绝-背包'
        WHEN 70807 THEN '拒绝-有时限'
        WHEN 70808 THEN '没东西可给'
        ELSE '未知'
    END AS `用途`
FROM `world`.`npc_text`
WHERE `ID` BETWEEN 70801 AND 70808
ORDER BY `ID`;


SELECT '=== 数量检查 ===' AS `步骤`;

SELECT
    COUNT(*) AS `应该是8`
FROM `world`.`npc_text`
WHERE `ID` BETWEEN 70801 AND 70808;


-- ============================================================================
--  第三部分：确认没有和上游文本ID撞号
-- ============================================================================

SELECT '=== 撞号检查：上游最大bot文本ID ===' AS `步骤`;

SELECT
    MAX(`ID`) AS `上游最大ID_应小于70801`
FROM `world`.`npc_text`
WHERE `ID` BETWEEN 70000 AND 70800;
