-- ############################################################################
--  一、NPCBot 改名
-- ############################################################################
--
--  【先搞清楚一件事】NPCBot 的名字是【按 entry 共享的】。
--  改了 entry=70001 的名字，所有 entry=70001 的 bot 都会跟着变。
--  如果你想让每只 bot 名字不同，需要给它们不同的 entry（那是另一件事）。
--
--  名字有两层：
--    creature_template.name         默认名（英文，所有语言的兜底）
--    creature_template_locale.Name  本地化名（zhCN 客户端优先看这个）
--
--  依据 Creature.cpp:3093 GetNameForLocaleIdx：
--    有 locale 名就用 locale 名，没有才用默认名。
--  所以【中英文可以共存】。


-- ----------------------------------------------------------------------------
--  1.1 先看看现在叫什么（把 70001 换成你的 entry）
-- ----------------------------------------------------------------------------
SELECT
    ct.`entry`,
    ct.`name`                AS '英文名(默认)',
    ctl.`Name`               AS '中文名(zhCN)'
FROM `world`.`creature_template` ct
LEFT JOIN `world`.`creature_template_locale` ctl
       ON ctl.`entry` = ct.`entry` AND ctl.`locale` = 'zhCN'
WHERE ct.`entry` = 70001;


-- ----------------------------------------------------------------------------
--  1.2 改【中文名】（推荐：不动原表，只加本地化）
-- ----------------------------------------------------------------------------
--  REPLACE = 有就覆盖，没有就插入
REPLACE INTO `world`.`creature_template_locale`
    (`entry`, `locale`, `Name`)
VALUES
    (70001, 'zhCN', '巫妖王');

--  执行后：.reload creature_template_locale
--  （或者重启服务端）


-- ----------------------------------------------------------------------------
--  1.3 改【英文名】（默认名）
-- ----------------------------------------------------------------------------
UPDATE `world`.`creature_template`
SET `name` = 'The Lich King'
WHERE `entry` = 70001;

--  执行后：.reload creature_template 70001


-- ----------------------------------------------------------------------------
--  1.4 批量改（比如把一批 bot 的中文名一次设好）
-- ----------------------------------------------------------------------------
REPLACE INTO `world`.`creature_template_locale`
    (`entry`, `locale`, `Name`)
VALUES
    (70001, 'zhCN', '巫妖王'),
    (70002, 'zhCN', '圣骑士'),
    (70003, 'zhCN', '大法师');
--  按需增删行。执行后 .reload creature_template_locale


