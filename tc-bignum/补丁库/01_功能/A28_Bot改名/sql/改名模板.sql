-- ############################################################################
--  二、PlayerBot 改名
-- ############################################################################
--
--  PlayerBot 是【真实角色】，名字在 characters 库，每个角色独立。
--
--  【执行前必须确认】这个角色【不在线】。
--  在线时改库，内存里还是旧名字，登出时会把旧名写回去 —— 白改。
--  在线的请用指令：.botname player <旧名> <新名>
--  或者先 .pbot despawn <名字> 让它下线。


-- ----------------------------------------------------------------------------
--  2.1 先确认它是谁、在不在线
-- ----------------------------------------------------------------------------
SELECT
    `guid`,
    `account`,
    `name`,
    `online`     -- 【必须是 0】才能用 SQL 改
FROM `characters`.`characters`
WHERE `name` = 'Evirstara';


-- ----------------------------------------------------------------------------
--  2.2 改名
-- ----------------------------------------------------------------------------
--  先查新名字有没有被占用（应该返回 0 行）
SELECT `guid`, `name` FROM `characters`.`characters` WHERE `name` = '阿尔萨斯';

--  确认没被占用后再执行下面这句
UPDATE `characters`.`characters`
SET `name` = '阿尔萨斯'
WHERE `name` = 'Evirstara'
  AND `online` = 0;          -- 双保险：在线就不改

--  变格名（俄语客户端用）要一起清掉，否则会对不上
DELETE FROM `characters`.`character_declinedname`
WHERE `guid` = (SELECT `guid` FROM `characters`.`characters` WHERE `name` = '阿尔萨斯');

--  执行后【必须重启服务端】。
--  原因：角色名有内存缓存（CharacterCache），
--        只改库不重启的话 /who、好友列表、组队框还是旧名。
--        用指令改就没这个问题（指令会调 sCharacterCache->UpdateCharacterData）。


-- ----------------------------------------------------------------------------
--  2.3 验证改完了
-- ----------------------------------------------------------------------------
SELECT `guid`, `name`, `online` FROM `characters`.`characters`
WHERE `name` IN ('Evirstara', '阿尔萨斯');


-- ############################################################################
--  三、中文名能不能用？能。但有一条规则要知道
-- ############################################################################
--
--  【PlayerBot 的名字不能中英混用】
--
--  这是暴雪原版规则，不是我们加的限制：
--    ObjectMgr.cpp:8633  isValidString()
--        if (isBasicLatinString(...)) return true;    // 纯英文 OK
--        if (isEastAsianString(...))  return true;    // 纯中日韩 OK
--        return false;                                // 混着写 -> 拒绝
--
--  所以：
--    '阿尔萨斯'    OK
--    'Arthas'      OK
--    '阿尔萨斯X'   拒绝（混用）
--    'Bot机器人'   拒绝（混用）
--
--  长度上限 12 个【字符】（不是字节），所以中文最多 12 个字。
--
--  【NPCBot 没有这个限制】—— Creature 的名字随便写，
--  中英混用、带空格、带标点都行，长度上限 100 字节。
--
--  另外：如果你的 worldserver.conf 里把
--      StrictPlayerNames = 1
--  中文就会被拒（那个值表示"只允许基础拉丁字母"）。
--  默认是 0，不用改。


-- ############################################################################
--  四、改完客户端还是显示旧名字？
-- ############################################################################
--
--  【这是正常现象，不是没改成功】
--
--  QueryHandler.cpp:119  客户端第一次见到某个 NPC entry 时会发
--  CMSG_CREATURE_QUERY 问名字，拿到后【存进本地缓存文件】，之后不再问。
--
--  解决办法（NPCBot）：
--    1. 关闭客户端
--    2. 删掉  你的客户端目录\Cache\WDB\zhCN\creaturecache.wdb
--    3. 重新登录
--
--  没缓存过这个 entry 的其他玩家会直接看到新名字。
--
--  PlayerBot（角色名）没有这个缓存问题，重启服务端即可。
