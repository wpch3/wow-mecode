-- 看看有哪些还没汉化（对照 bottext.h 的 401 个ID）
SELECT t.`ID`, LEFT(t.`text0_0`, 60) AS `英文原文`
FROM `world`.`npc_text` t
LEFT JOIN `world`.`npc_text_locale` l
       ON l.`ID` = t.`ID` AND l.`Locale` = 'zhCN'
WHERE t.`ID` BETWEEN 70001 AND 70700
  AND l.`ID` IS NULL
ORDER BY t.`ID`
LIMIT 40;
